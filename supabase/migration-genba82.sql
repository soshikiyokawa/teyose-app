-- ── 入れたあとの確認 ──
--
-- 人ごとの件数と期間。8人・計60件になっていれば取り込めている
select person as "社員大工", count(*) as "件数",
       min(start_date) as "いちばん早い日", max(end_date) as "いちばん遅い日"
  from public.staff_assignments
 group by person
 order by 2 desc, 1;

-- 同じ人の配置が日付で重なっていないか（0件なら問題なし）
select a.person as "社員大工", a.project_name as "現場1", b.project_name as "現場2",
       a.start_date as "開始1", a.end_date as "終了1", b.start_date as "開始2", b.end_date as "終了2"
  from public.staff_assignments a
  join public.staff_assignments b
    on a.person = b.person and a.id < b.id
   and a.start_date <= b.end_date and b.start_date <= a.end_date
 order by 1, 4;
